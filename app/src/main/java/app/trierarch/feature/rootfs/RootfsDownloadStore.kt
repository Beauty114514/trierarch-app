package app.trierarch.feature.rootfs

import java.io.File
import org.tomlj.Toml

data class DownloadedRootfs(
    val file: String,
    val product: String,
    val source: String,
    val sha256: String,
    val size: Long,
    val downloadedAt: Long,
)

/**
 * The persistent `files/downloads/rootfs` store. It only keeps archives; it
 * never extracts or registers a runtime rootfs.
 */
class RootfsDownloadStore(private val directory: File) {
    init {
        directory.mkdirs()
    }

    @Synchronized
    fun list(): List<DownloadedRootfs> =
        readEntries().values
            .filter { entry -> File(directory, entry.file).isFile }
            .sortedBy { it.file }

    @Synchronized
    fun record(image: LxcImage, file: File, downloadedAt: Long = System.currentTimeMillis()) {
        val entries = readEntries().toMutableMap()
        entries[file.name] = DownloadedRootfs(
            file = file.name,
            product = image.product,
            source = image.downloadUrl,
            sha256 = image.sha256,
            size = file.length(),
            downloadedAt = downloadedAt,
        )
        write(entries)
    }

    @Synchronized
    fun remove(fileName: String): DownloadedRootfs? {
        val entries = readEntries().toMutableMap()
        val removed = entries.remove(fileName) ?: return null
        File(directory, removed.file).delete()
        write(entries)
        return removed
    }

    fun file(name: String): File = File(directory, name)

    fun fileFor(image: LxcImage): File = File(directory, image.fileName)

    fun indexFile(): File = File(directory, INDEX)

    private fun readEntries(): Map<String, DownloadedRootfs> {
        val index = File(directory, INDEX)
        if (!index.isFile) return emptyMap()
        return runCatching {
            val parsed = Toml.parse(index.readText())
            if (parsed.hasErrors()) return@runCatching emptyMap()
            val array = parsed.getArray("downloads") ?: return@runCatching emptyMap()
            (0 until array.size()).mapNotNull { position ->
                val entry = array.getTable(position) ?: return@mapNotNull null
                val file = entry.getString("file") ?: return@mapNotNull null
                DownloadedRootfs(
                    file = file,
                    product = entry.getString("product") ?: "",
                    source = entry.getString("source") ?: "",
                    sha256 = entry.getString("sha256") ?: "",
                    size = entry.getLong("size") ?: 0L,
                    downloadedAt = entry.getLong("downloadedAt") ?: 0L,
                )
            }.associateBy { it.file }
        }.getOrDefault(emptyMap())
    }

    private fun write(entries: Map<String, DownloadedRootfs>) {
        check(directory.isDirectory || directory.mkdirs()) {
            "cannot create ${directory.absolutePath}"
        }
        val text = buildString {
            appendLine("# Generated by the Rootfs screen. Archives only; no extraction.")
            entries.values.sortedBy { it.file }.forEach { entry ->
                appendLine()
                appendLine("[[downloads]]")
                appendLine("file = ${tomlString(entry.file)}")
                appendLine("product = ${tomlString(entry.product)}")
                appendLine("source = ${tomlString(entry.source)}")
                appendLine("sha256 = ${tomlString(entry.sha256)}")
                appendLine("size = ${entry.size}")
                appendLine("downloadedAt = ${entry.downloadedAt}")
            }
        }
        File(directory, INDEX).writeText(text)
    }

    private fun tomlString(value: String): String =
        "\"" + value.replace("\\", "\\\\").replace("\"", "\\\"") + "\""

    companion object {
        const val INDEX = "index.toml"
        const val DIRECTORY = "downloads/rootfs"
    }
}
