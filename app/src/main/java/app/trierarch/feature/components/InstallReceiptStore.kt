package app.trierarch.feature.components

import app.trierarch.update.InstallReceipt
import java.io.File
import org.tomlj.Toml

/** Persistent receipts for package installs, keyed by target and release. */
class InstallReceiptStore(private val directory: File) {
    fun all(): List<InstallReceipt> =
        read().values.sortedWith(compareBy({ it.target }, { it.componentId }, { it.releaseVersion }))

    fun receipt(target: String, componentId: String, releaseVersion: String?): InstallReceipt? =
        read()[key(target, componentId, releaseVersion)]

    fun record(receipt: InstallReceipt) {
        val entries = read().toMutableMap()
        entries[key(receipt.target, receipt.componentId, receipt.releaseVersion)] = receipt
        write(entries)
    }

    fun remove(target: String, componentId: String, releaseVersion: String?) {
        val entries = read().toMutableMap()
        entries.remove(key(target, componentId, releaseVersion))
        write(entries)
    }

    private fun read(): Map<String, InstallReceipt> {
        val file = File(directory, FILE)
        if (!file.isFile) return emptyMap()
        val parsed = runCatching { Toml.parse(file.readText()) }.getOrNull() ?: return emptyMap()
        if (parsed.hasErrors()) return emptyMap()
        val array = parsed.getArray("receipts") ?: return emptyMap()
        return (0 until array.size()).mapNotNull { index ->
            val table = array.getTable(index) ?: return@mapNotNull null
            val target = table.getString("target") ?: return@mapNotNull null
            val componentId = table.getString("componentId") ?: return@mapNotNull null
            val releaseVersion = table.getString("releaseVersion")
            val packages = table.getTable("packages")?.toMap().orEmpty()
                .mapValues { (_, value) -> value.toString() }
            val receipt = InstallReceipt(target, componentId, releaseVersion, packages)
            key(target, componentId, releaseVersion) to receipt
        }.toMap()
    }

    private fun write(entries: Map<String, InstallReceipt>) {
        check(directory.isDirectory || directory.mkdirs()) {
            "cannot create ${directory.absolutePath}"
        }
        val text = buildString {
            appendLine("# Generated by the Rootfs component installer. Do not edit by hand.")
            entries.values.sortedWith(
                compareBy({ it.target }, { it.componentId }, { it.releaseVersion }),
            ).forEach { receipt ->
                appendLine()
                appendLine("[[receipts]]")
                appendLine("target = ${quote(receipt.target)}")
                appendLine("componentId = ${quote(receipt.componentId)}")
                receipt.releaseVersion?.let { appendLine("releaseVersion = ${quote(it)}") }
                appendLine(
                    "packages = {" + receipt.packages.toSortedMap().entries.joinToString(", ") {
                        "${quote(it.key)} = ${quote(it.value)}"
                    } + "}",
                )
            }
        }
        File(directory, FILE).writeText(text)
    }

    private fun key(target: String, componentId: String, releaseVersion: String?): String =
        "$target\u0000$componentId\u0000${releaseVersion.orEmpty()}"

    private fun quote(value: String): String =
        "\"" + value.replace("\\", "\\\\").replace("\"", "\\\"") + "\""

    companion object {
        const val FILE = "receipts.toml"
    }
}
