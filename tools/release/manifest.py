#!/usr/bin/env python3
"""Generate manifest.toml from a GitHub release and components.toml.

The manifest is the app's only update feed. Run this after uploading the APK
and companion files, then commit the generated manifest.toml.

Usage:
    python3 tools/release/manifest.py --tag v0.6.0
    python3 tools/release/manifest.py --tag latest
"""

from __future__ import annotations

import argparse
import json
import os
import re
import sys
import tomllib
import urllib.error
import urllib.parse
import urllib.request
from pathlib import Path

API = "https://api.github.com"
DEFAULT_REPO = "Beauty114514/trierarch-app"
SHA256 = re.compile(r"^[0-9a-f]{64}$")


class ManifestError(RuntimeError):
    pass


def github_get(path: str) -> dict:
    headers = {
        "Accept": "application/vnd.github+json",
        "User-Agent": "trierarch-manifest",
    }
    token = os.environ.get("GITHUB_TOKEN")
    if token:
        headers["Authorization"] = f"Bearer {token}"
    request = urllib.request.Request(API + path, headers=headers)
    try:
        with urllib.request.urlopen(request, timeout=30) as response:
            return json.load(response)
    except urllib.error.HTTPError as error:
        body = error.read().decode(errors="replace")[:300]
        raise ManifestError(f"GitHub API {error.code}: {body}") from error
    except urllib.error.URLError as error:
        raise ManifestError(f"cannot reach GitHub: {error.reason}") from error


def release_for(repo: str, tag: str) -> dict:
    if tag == "latest":
        path = f"/repos/{repo}/releases/latest"
    else:
        path = f"/repos/{repo}/releases/tags/{urllib.parse.quote(tag, safe='')}"
    return github_get(path)


def parse_gradle(path: Path) -> tuple[int, str]:
    text = path.read_text()
    code = re.search(r"(?m)^\s*versionCode\s*=\s*(\d+)\s*$", text)
    name = re.search(r'(?m)^\s*versionName\s*=\s*"([^"]+)"\s*$', text)
    if not code or not name:
        raise ManifestError(f"cannot read versionCode/versionName from {path}")
    return int(code.group(1)), name.group(1)


def asset_digest(asset: dict) -> str:
    digest = (asset.get("digest") or "").lower()
    if not digest.startswith("sha256:"):
        raise ManifestError(
            f"GitHub did not report a SHA-256 digest for {asset.get('name')}; "
            "re-upload the asset or add the digest manually"
        )
    value = digest[len("sha256:"):]
    if not SHA256.fullmatch(value):
        raise ManifestError(f"invalid digest for {asset.get('name')}: {digest}")
    return value


def find_asset(release: dict, name: str) -> dict:
    for asset in release.get("assets") or []:
        if asset.get("name") == name:
            return asset
    available = ", ".join(sorted(a.get("name", "") for a in release.get("assets") or []))
    raise ManifestError(
        f"{name} is not in release {release.get('tag_name')}; assets: {available}"
    )


def find_apk(release: dict, version_name: str, override: str | None) -> dict:
    if override:
        return find_asset(release, override)
    preferred = f"trierarch-{version_name}.apk".lower()
    for asset in release.get("assets") or []:
        if (asset.get("name") or "").lower() == preferred:
            return asset
    apks = [
        asset
        for asset in release.get("assets") or []
        if (asset.get("name") or "").lower().endswith(".apk")
    ]
    if len(apks) == 1:
        return apks[0]
    if not apks:
        raise ManifestError(f"no APK in release {release.get('tag_name')}")
    names = ", ".join(asset["name"] for asset in apks)
    raise ManifestError(f"cannot pick the APK automatically ({names}); pass --apk")


def toml_string(value: str) -> str:
    escaped = value.replace("\\", "\\\\").replace('"', '\\"')
    return f'"{escaped}"'


def render_manifest(
    repo: str,
    version_code: int,
    version_name: str,
    release: dict,
    apk: dict,
    components: list[dict],
    releases: dict[str, dict],
) -> str:
    lines = [
        "# Generated by tools/release/manifest.py. Do not edit by hand.",
        "schema = 1",
        "",
        "[app]",
        f"versionCode = {version_code}",
        f"versionName = {toml_string(version_name)}",
        f"apkUrl = {toml_string(apk['browser_download_url'])}",
        f"apkSize = {int(apk['size'])}",
        f"apkSha256 = {toml_string(asset_digest(apk))}",
    ]
    notes_url = release.get("html_url")
    if notes_url:
        lines.append(f"notesUrl = {toml_string(notes_url)}")

    seen = set()
    for component in components:
        comp_id = component.get("id")
        if not comp_id:
            raise ManifestError("a component in components.toml has no id")
        if comp_id in seen:
            raise ManifestError(f"duplicate component id: {comp_id}")
        seen.add(comp_id)
        name = component.get("file")
        if not name:
            raise ManifestError(f"component {comp_id} has no file")
        tag = component.get("tag")
        if not tag or tag == release.get("tag_name"):
            component_release = release
        else:
            component_release = releases.get(tag)
            if component_release is None:
                component_release = release_for(repo, tag)
                releases[tag] = component_release
        asset = find_asset(component_release, name)
        lines.extend(
            [
                "",
                "[[components]]",
                f"id = {toml_string(comp_id)}",
                f"name = {toml_string(component['name'])}",
            ]
        )
        if component.get("version"):
            lines.append(f"version = {toml_string(component['version'])}")
        lines.extend(
            [
                f"file = {toml_string(name)}",
                f"url = {toml_string(asset['browser_download_url'])}",
                f"size = {int(asset['size'])}",
                f"sha256 = {toml_string(asset_digest(asset))}",
            ]
        )
    return "\n".join(lines) + "\n"


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--tag", default="latest", help="release tag, or 'latest'")
    parser.add_argument("--repo", default=DEFAULT_REPO, help="GitHub repository")
    parser.add_argument("--apk", help="APK asset name when it cannot be inferred")
    parser.add_argument(
        "--output",
        default=None,
        help="output path; defaults to manifest.toml in the repository root",
    )
    args = parser.parse_args()

    repo_root = Path(__file__).resolve().parents[2]
    components_path = repo_root / "tools/release/components.toml"
    version_code, version_name = parse_gradle(repo_root / "app/build.gradle.kts")
    components = tomllib.loads(components_path.read_text()).get("components") or []
    if not components:
        raise ManifestError(f"no components in {components_path}")

    release = release_for(args.repo, args.tag)
    apk = find_apk(release, version_name, args.apk)
    manifest = render_manifest(
        args.repo, version_code, version_name, release, apk, components, {}
    )

    output = Path(args.output) if args.output else repo_root / "manifest.toml"
    if str(output) == "-":
        sys.stdout.write(manifest)
    else:
        output.write_text(manifest)
        print(f"wrote {output}", file=sys.stderr)
        print(f"  app {version_name} (versionCode {version_code})", file=sys.stderr)
        print(f"  {len(components)} component(s) from {release.get('tag_name')}", file=sys.stderr)
    return 0


if __name__ == "__main__":
    try:
        raise SystemExit(main())
    except ManifestError as error:
        print(f"manifest: {error}", file=sys.stderr)
        raise SystemExit(1)
